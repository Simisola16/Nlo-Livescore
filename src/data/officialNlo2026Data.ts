// Canonical Venue Name Normalization Map (merges case & alias variations from official sheets)
export function normalizeOfficialVenueName(raw: string): string {
  const trimmed = raw.trim().toUpperCase().replace(/\s+/g, ' ');
  if (trimmed === 'GOAL PROJECT, MKO,FCT' || trimmed === 'GOAL PROJECT, MKO, FCT') {
    return 'FIFA GOAL PROJECT ABUJA';
  }
  if (trimmed === 'AREA 3 PITCH ABUJA') {
    return 'AREA 3 PITCH ABUJA';
  }
  if (trimmed === 'UYO TOWNSHIP STADIUM') {
    return 'UYO TOWNSHIP STADIUM';
  }
  if (trimmed === 'ENYIMBA STADIUM') {
    return 'ENYIMBA STADIUM';
  }
  return trimmed;
}

type RawRow = [
  matchNumber: number,
  weekNumber: number,
  legHalf: 'FIRST_HALF' | 'SECOND_HALF',
  homeTeam: string,
  awayTeam: string,
  venue: string,
  matchDate: string,
  kickoffTime: string,
  refImage: string,
  notes?: string,
];

function buildGroupFixtures(
  groupCode: SeedFixtureEntry['groupCode'],
  rows: RawRow[]
): SeedFixtureEntry[] {
  return rows.map(([mNo, week, leg, home, away, venue, date, time, img, notes]) => {
    const isHomeBye = home.startsWith('BYE');
    const isAwayBye = away.startsWith('BYE');
    const isBye = isHomeBye || isAwayBye;

    if (isBye) {
      const restingTeam = isHomeBye ? away : home;
      return {
        groupCode,
        matchNumber: mNo,
        weekNumber: week,
        legHalf: leg,
        isBye: true,
        homeTeamName: isHomeBye ? null : home,
        awayTeamName: isAwayBye ? null : away,
        byeTeamName: restingTeam,
        byeLabel: isHomeBye ? home : away,
        venueName: null,
        matchDate: null,
        kickoffTime: null,
        isKickoffTbc: false,
        sourceReferenceImage: img,
        sheetNotes: notes ?? 'Scheduled BYE week (Non-playable scheduling entry)',
      };
    }

    return {
      groupCode,
      matchNumber: mNo,
      weekNumber: week,
      legHalf: leg,
      isBye: false,
      homeTeamName: home,
      awayTeamName: away,
      byeTeamName: null,
      byeLabel: null,
      venueName: normalizeOfficialVenueName(venue),
      matchDate: date,
      kickoffTime: time,
      isKickoffTbc: time === 'TBC',
      sourceReferenceImage: img,
      sheetNotes: notes ?? null,
    };
  });
}

